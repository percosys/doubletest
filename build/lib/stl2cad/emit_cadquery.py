"""Emit a CadQuery script from a recipe (text only; running it needs `cadquery`)."""

from __future__ import annotations

from .recipe import Recipe

HEADER = '''"""Generated by stl2cad. Edit the recipe, not this file."""
import cadquery as cq

V = cq.Vector
'''


def emit(recipe: Recipe) -> str:
    x, y, z = recipe.stock
    lines = [HEADER, f"part = cq.Workplane('XY').box({x}, {y}, {z}, centered=False)  # stock ({recipe.units})"]
    for h in recipe.holes:
        cx, cy, cz = h["center"]
        ax = h["axis"]
        # Cut a cylinder longer than the stock so it passes fully through.
        length = max(recipe.stock) * 2
        px, py, pz = (cx - ax[0] * length / 2, cy - ax[1] * length / 2, cz - ax[2] * length / 2)
        lines.append(
            f"part = part.cut(cq.Workplane('XY').add(cq.Solid.makeCylinder("
            f"{h['diameter'] / 2}, {length}, V({px:.4f}, {py:.4f}, {pz:.4f}), "
            f"V({ax[0]:.4f}, {ax[1]:.4f}, {ax[2]:.4f}))).val())"
            f"  # {h['id']}: {h.get('standard') or 'measured'}"
        )
    lines.append("")
    lines.append("if __name__ == '__main__':")
    lines.append("    cq.exporters.export(part, 'model.step')")
    return "\n".join(lines) + "\n"
